class Demo2
{
  public static void main (String arg[])
  {
    int a = 10;
    byte b = (byte)a;       //explict typecasting
    System.out.println(b);   // 10 - byte date
   
   double c = 52.6;
   int d = (int)c;          // explict typecasting
   System.out.println(d);    // 52 int data

   double e = 62.3;
   long f = (long)e ;        // explict typecasting
   System.out.println(f);    // 62- long data 
  
   
  }
}